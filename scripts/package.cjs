const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { execFileSync } = require('node:child_process');
const root = path.resolve(__dirname, '..');
const out = process.env.AIRVIEW_OUTPUT_DIR || path.join(root, 'dist');
const appDir = path.join(out,'Airview-Windows-x64');
if (process.platform !== 'win32') throw new Error('Build on Windows to create the Windows package.');
if (fs.existsSync(appDir)) throw new Error('The output folder already exists. Remove or archive it before rebuilding.');
const electronDir = process.env.AIRVIEW_ELECTRON_DIST || path.dirname(require('electron'));
fs.mkdirSync(out,{recursive:true});
fs.cpSync(electronDir,appDir,{recursive:true});
const originalExe=fs.existsSync(path.join(appDir,'electron.exe'))?'electron.exe':'BoyhoodRadar.exe';fs.renameSync(path.join(appDir,originalExe),path.join(appDir,'Airview.exe'));
const resources=path.join(appDir,'resources','app');fs.mkdirSync(resources,{recursive:true});
for(const dir of ['src','assets'])fs.cpSync(path.join(root,dir),path.join(resources,dir),{recursive:true});
const pkg = require('../package.json');delete pkg.devDependencies;delete pkg.scripts;
fs.writeFileSync(path.join(resources,'package.json'),JSON.stringify(pkg,null,2));
for(const name of ['README.md','THIRD_PARTY_NOTICES.md','PERFORMANCE.md'])fs.copyFileSync(path.join(root,name),path.join(appDir,name));
fs.copyFileSync(path.join(root,'LICENSE'),path.join(appDir,'LICENSE-Airview.txt'));
fs.writeFileSync(path.join(appDir,'README-FIRST.txt'),'AIRVIEW 2.2.1\r\n\r\nExtract the entire ZIP, then open Airview.exe. Windows 10/11 x64. Free portable app, no account or installation. Preferences and caches stay in Airview-data beside the executable. The app is not commercially signed. Read README.md for sources and limitations. Personal observation only.\r\n','utf8');
const archive=path.join(out,'Airview-2.2.1-Windows-x64.zip');
execFileSync('tar',['-a','-c','-f',archive,'-C',out,path.basename(appDir)],{stdio:'inherit'});
const sha=crypto.createHash('sha256').update(fs.readFileSync(archive)).digest('hex');
fs.writeFileSync(archive+'.sha256',sha+'  '+path.basename(archive)+'\n');
console.log(JSON.stringify({archive,sha256:sha,bytes:fs.statSync(archive).size}));

