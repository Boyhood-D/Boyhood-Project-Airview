const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { execFileSync } = require('node:child_process');
const root = path.resolve(__dirname, '..');
const out = path.join(root, 'dist');
const appDir = path.join(out,'BoyhoodRadar-Windows-x64');
if (process.platform !== 'win32') throw new Error('Construire sur Windows pour produire le paquet Windows.');
if (fs.existsSync(appDir)) throw new Error('Le dossier de sortie existe déjà. Archive-le ou supprime-le avant une nouvelle compilation.');
const electronDir = path.dirname(require('electron'));
fs.mkdirSync(out,{recursive:true});
fs.cpSync(electronDir,appDir,{recursive:true});
fs.renameSync(path.join(appDir,'electron.exe'),path.join(appDir,'BoyhoodRadar.exe'));
const resources=path.join(appDir,'resources','app');fs.mkdirSync(resources,{recursive:true});
for(const dir of ['src','assets'])fs.cpSync(path.join(root,dir),path.join(resources,dir),{recursive:true});
const pkg = require('../package.json');delete pkg.devDependencies;delete pkg.scripts;
fs.writeFileSync(path.join(resources,'package.json'),JSON.stringify(pkg,null,2));
for(const name of ['README.md','THIRD_PARTY_NOTICES.md'])fs.copyFileSync(path.join(root,name),path.join(appDir,name));
fs.copyFileSync(path.join(root,'LICENSE'),path.join(appDir,'LICENSE-BoyhoodRadar.txt'));
fs.writeFileSync(path.join(appDir,'LIRE-MOI.txt'),'BOYHOOD RADAR 1.0.0\r\n\r\nExtraire tout le ZIP dans un dossier, puis ouvrir BoyhoodRadar.exe.\r\nWindows 10/11 64 bits. Internet requis pour le trafic.\r\nGratuit, sans compte, sans installation.\r\nLes préférences et le cache restent dans BoyhoodRadar-data à côté du programme.\r\nNe pas lancer depuis le ZIP ou un dossier protégé en écriture.\r\nApplication non signée : Windows peut avertir de son origine.\r\nLire README.md pour les sources, limites et commandes.\r\nObservation personnelle uniquement, pas de contrôle aérien réel.\r\n','utf8');
const archive=path.join(out,'BoyhoodRadar-1.0.0-Windows-x64.zip');
execFileSync('tar',['-a','-c','-f',archive,'-C',out,path.basename(appDir)],{stdio:'inherit'});
const sha=crypto.createHash('sha256').update(fs.readFileSync(archive)).digest('hex');
fs.writeFileSync(archive+'.sha256',sha+'  '+path.basename(archive)+'\n');
console.log(JSON.stringify({archive,sha256:sha,bytes:fs.statSync(archive).size}));
